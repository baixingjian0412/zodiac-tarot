// 洗牌
function shuffleDeck() {
  const deck = [...TAROT_MAJOR];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

// 抽一张牌
function drawCard() {
  const deck = shuffleDeck();
  const card = deck[0];
  const isReversed = Math.random() < 0.3;
  return {
    ...card,
    isReversed,
    reading: isReversed ? card.reversed : card.upright,
    direction: isReversed ? '逆位' : '正位'
  };
}

// 三张牌阵
function drawThreeCards() {
  const deck = shuffleDeck();
  return deck.slice(0, 3).map((card, i) => {
    const isReversed = Math.random() < 0.3;
    const positions = ['过去', '现在', '未来'];
    return {
      ...card,
      isReversed,
      reading: isReversed ? card.reversed : card.upright,
      direction: isReversed ? '逆位' : '正位',
      position: positions[i]
    };
  });
}

// 格式化每日塔罗牌
function formatDailyCard(card, isReversed) {
  return {
    ...card,
    isReversed,
    reading: isReversed ? card.reversed : card.upright,
    direction: isReversed ? '逆位' : '正位'
  };
}

// 今日塔罗 — 检查localStorage是否有用户手动覆盖，否则基于日期
function getDailyTarot() {
  const stored = localStorage.getItem('dailyTarotOverride');
  if (stored) {
    try {
      const override = JSON.parse(stored);
      const today = new Date();
      const dateKey = today.getFullYear() + '-' + (today.getMonth()+1) + '-' + today.getDate();
      if (override.date === dateKey) {
        const card = TAROT_MAJOR.find(c => c.id === override.cardId);
        if (card) return formatDailyCard(card, override.isReversed);
      }
    } catch(e) { /* ignore corrupt data */ }
  }

  // 默认：基于日期的确定性选择
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth()+1) * 100 + today.getDate();
  const idx = seed % TAROT_MAJOR.length;
  const card = TAROT_MAJOR[idx];
  const isReversed = (seed + 7) % 11 === 0;
  return formatDailyCard(card, isReversed);
}

// 手动重新抽取今日塔罗（随机选择，存入localStorage覆盖）
function rerollDailyTarot() {
  const deck = shuffleDeck();
  const card = deck[0];
  const isReversed = Math.random() < 0.3;
  const today = new Date();
  const dateKey = today.getFullYear() + '-' + (today.getMonth()+1) + '-' + today.getDate();
  localStorage.setItem('dailyTarotOverride', JSON.stringify({
    date: dateKey,
    cardId: card.id,
    isReversed
  }));
  return formatDailyCard(card, isReversed);
}
