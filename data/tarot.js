// 洗牌
function shuffleDeck() {
  const deck = [...TAROT_MAJOR];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

// 抽一张牌
function drawCard() {
  const deck = shuffleDeck();
  const card = deck[0];
  const isReversed = Math.random() < 0.3;
  return {
    ...card,
    isReversed,
    reading: isReversed ? card.reversed : card.upright,
    direction: isReversed ? '逆位' : '正位'
  };
}

// 三张牌阵
function drawThreeCards() {
  const deck = shuffleDeck();
  return deck.slice(0, 3).map((card, i) => {
    const isReversed = Math.random() < 0.3;
    const positions = ['过去', '现在', '未来'];
    return {
      ...card,
      isReversed,
      reading: isReversed ? card.reversed : card.upright,
      direction: isReversed ? '逆位' : '正位',
      position: positions[i]
    };
  });
}

// 今日塔罗（基于日期选择）
function getDailyTarot() {
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth()+1) * 100 + today.getDate();
  const idx = seed % TAROT_MAJOR.length;
  const card = TAROT_MAJOR[idx];
  const isReversed = (seed + 7) % 11 === 0; // 约9%概率逆位
  return {
    ...card,
    isReversed,
    reading: isReversed ? card.reversed : card.upright,
    direction: isReversed ? '逆位' : '正位'
  };
}
